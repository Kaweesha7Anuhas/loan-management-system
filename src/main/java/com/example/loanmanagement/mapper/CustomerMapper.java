package com.example.loanmanagement.mapper;

import com.example.loanmanagement.dto.request.CreateCustomerRequest;
import com.example.loanmanagement.dto.request.UpdateCustomerRequest;
import com.example.loanmanagement.dto.response.CustomerResponse;
import com.example.loanmanagement.dto.response.CustomerSummaryResponse;
import com.example.loanmanagement.entity.Customer;
import com.example.loanmanagement.enums.CustomerStatus;
import org.springframework.stereotype.Component;

/**
 * Entity ↔ DTO translation for Customer.
 *
 * Why a manual mapper (no MapStruct)?
 *  - No extra dependency / annotation processor.
 *  - Explicit control over which fields are copied and which are not
 *    (id, customerCode, timestamps — never from the request).
 *  - Easier to debug — the code IS the mapping.
 *  - For a project this size, MapStruct's boilerplate savings don't
 *    justify the build-time complexity.
 *
 * NOT responsible for:
 *  - Generating customerCode (done in CustomerService using IdGenerator).
 *  - Checking duplicates (done in CustomerService against the repository).
 *  - Validation (done by @Valid on the DTO).
 */
@Component
public class CustomerMapper {

    /**
     * Full detail DTO — used by GET /:id and returned from POST/PUT.
     */
    public CustomerResponse toResponse(Customer entity) {
        if (entity == null) {
            return null;
        }
        return CustomerResponse.builder()
                .id(entity.getId())
                .customerCode(entity.getCustomerCode())
                .firstName(entity.getFirstName())
                .lastName(entity.getLastName())
                .fullName(entity.getFullName())
                .nicNumber(entity.getNicNumber())
                .dateOfBirth(entity.getDateOfBirth())
                .email(entity.getEmail())
                .phoneNumber(entity.getPhoneNumber())
                .address(entity.getAddress())
                .city(entity.getCity())
                .occupation(entity.getOccupation())
                .monthlyIncome(entity.getMonthlyIncome())
                .customerStatus(entity.getCustomerStatus())
                .createdAt(entity.getCreatedAt())
                .updatedAt(entity.getUpdatedAt())
                .build();
    }

    /**
     * Summary DTO — used in paginated list views.
     */
    public CustomerSummaryResponse toSummary(Customer entity) {
        if (entity == null) {
            return null;
        }
        return CustomerSummaryResponse.builder()
                .id(entity.getId())
                .customerCode(entity.getCustomerCode())
                .fullName(entity.getFullName())
                .nicNumber(entity.getNicNumber())
                .phoneNumber(entity.getPhoneNumber())
                .email(entity.getEmail())
                .customerStatus(entity.getCustomerStatus())
                .build();
    }

    /**
     * Map a CreateCustomerRequest to a new Customer entity.
     * Does NOT set customerCode — that's generated by the service
     * (because it depends on the current database state).
     */
    public Customer toEntity(CreateCustomerRequest request) {
        return Customer.builder()
                .firstName(request.getFirstName().trim())
                .lastName(request.getLastName().trim())
                .nicNumber(request.getNicNumber().trim().toUpperCase())
                .dateOfBirth(request.getDateOfBirth())
                .email(request.getEmail().trim().toLowerCase())
                .phoneNumber(request.getPhoneNumber().trim())
                .address(request.getAddress().trim())
                .city(trimOrNull(request.getCity()))
                .occupation(trimOrNull(request.getOccupation()))
                .monthlyIncome(request.getMonthlyIncome())
                .customerStatus(CustomerStatus.ACTIVE)
                .build();
    }

    /**
     * Update an EXISTING Customer from an UpdateCustomerRequest.
     * Does NOT touch: id, customerCode, nicNumber, customerStatus, createdAt.
     * Those are immutable through this endpoint.
     */
    public void updateEntity(Customer entity, UpdateCustomerRequest request) {
        entity.setFirstName(request.getFirstName().trim());
        entity.setLastName(request.getLastName().trim());
        entity.setDateOfBirth(request.getDateOfBirth());
        entity.setEmail(request.getEmail().trim().toLowerCase());
        entity.setPhoneNumber(request.getPhoneNumber().trim());
        entity.setAddress(request.getAddress().trim());
        entity.setCity(trimOrNull(request.getCity()));
        entity.setOccupation(trimOrNull(request.getOccupation()));
        entity.setMonthlyIncome(request.getMonthlyIncome());
    }

    // ─────────────────────────────────────────────
    // Helper
    // ─────────────────────────────────────────────

    private String trimOrNull(String value) {
        if (value == null) {
            return null;
        }
        String trimmed = value.trim();
        return trimmed.isEmpty() ? null : trimmed;
    }
}