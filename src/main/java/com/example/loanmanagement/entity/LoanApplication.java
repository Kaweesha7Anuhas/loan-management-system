package com.example.loanmanagement.entity;

import com.example.loanmanagement.enums.ApplicationStatus;
import com.example.loanmanagement.enums.RecommendationDecision;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * A customer's application for a loan. Moves through the workflow state machine
 * (DRAFT → SUBMITTED → UNDER_REVIEW → RECOMMENDED → APPROVED/REJECTED), with
 * each transition recorded in ApplicationHistory.
 *
 * Snapshot fields (annualInterestRate, requestedAmount, requestedTenureMonths):
 * these are COPIED from the LoanType at submission time. Editing the LoanType
 * later does not change this application. This is fundamental to preserving
 * the financial agreement a customer was quoted.
 *
 * No @Data — see User.java rationale.
 */
@Entity
@Table(
    name = "loan_applications",
    indexes = {
        @Index(name = "idx_app_app_number", columnList = "application_number"),
        @Index(name = "idx_app_customer",   columnList = "customer_id"),
        @Index(name = "idx_app_loan_type",  columnList = "loan_type_id"),
        @Index(name = "idx_app_status",     columnList = "application_status")
    }
)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class LoanApplication {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Human-readable unique identifier, e.g. "APP-202601-000001".
     * Generated by LoanApplicationService — format is a business concern.
     */
    @Column(name = "application_number", nullable = false, unique = true, length = 30)
    private String applicationNumber;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "customer_id", nullable = false)
    private Customer customer;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "loan_type_id", nullable = false)
    private LoanType loanType;

    // ─────────────────────────────────────────────
    // SNAPSHOT FIELDS — copied from LoanType at submission
    // ─────────────────────────────────────────────

    @Column(name = "requested_amount", nullable = false, precision = 15, scale = 2)
    private BigDecimal requestedAmount;

    /**
     * Interest rate applied to THIS application. Frozen at submission time.
     * A later change to LoanType.annualInterestRate must NOT update this field.
     */
    @Column(name = "annual_interest_rate", nullable = false, precision = 5, scale = 2)
    private BigDecimal annualInterestRate;

    @Column(name = "requested_tenure_months", nullable = false)
    private Integer requestedTenureMonths;

    // ─────────────────────────────────────────────
    // Workflow state
    // ─────────────────────────────────────────────

    @Column(name = "application_date", nullable = false)
    private LocalDate applicationDate;

    @Enumerated(EnumType.STRING)
    @Column(name = "application_status", nullable = false, length = 20)
    @Builder.Default
    private ApplicationStatus applicationStatus = ApplicationStatus.DRAFT;

    @Column(name = "purpose", length = 500)
    private String purpose;

    /**
     * Remarks written by the Loan Officer during review.
     */
    @Column(name = "officer_remarks", length = 1000)
    private String officerRemarks;

    /**
     * Final remarks written by the Admin on approval/rejection.
     */
    @Column(name = "admin_remarks", length = 1000)
    private String adminRemarks;

    /**
     * Direction of the officer's recommendation.
     * NULL until status becomes RECOMMENDED.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "recommended_decision", length = 30)
    private RecommendationDecision recommendedDecision;

    // ─────────────────────────────────────────────
    // Who did what
    // ─────────────────────────────────────────────

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "created_by", nullable = false, updatable = false)
    private User createdBy;

    /**
     * The Loan Officer who performed the review and recommended a decision.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "reviewed_by")
    private User reviewedBy;

    /**
     * The Admin who made the final approve/reject decision.
     * Kept separate from reviewedBy for separation-of-duties reporting.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "decided_by")
    private User decidedBy;

    @Column(name = "decision_date")
    private LocalDateTime decisionDate;

    // ─────────────────────────────────────────────
    // Timestamps
    // ─────────────────────────────────────────────

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        this.createdAt = now;
        this.updatedAt = now;
        if (this.applicationDate == null) {
            this.applicationDate = LocalDate.now();
        }
    }

    @PreUpdate
    protected void onUpdate() {
        this.updatedAt = LocalDateTime.now();
    }
}