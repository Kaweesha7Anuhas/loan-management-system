package com.example.loanmanagement.entity;

import com.example.loanmanagement.enums.PaymentMethod;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * A single payment received from a customer against a loan.
 *
 * This is a historical receipt — once recorded, it is NEVER edited or deleted.
 * Corrections use a reversal entry (a future reversal entity) rather than a
 * mutation, so the audit trail stays intact.
 *
 * A single repayment may be allocated across multiple instalments (e.g., a
 * customer pays 2 EMI worth in one lump sum). The allocation logic lives in
 * RepaymentService (Phase 11) and updates RepaymentSchedule.paidAmount /
 * remainingAmount for each affected instalment, plus Loan.totalPaid /
 * outstandingBalance on the parent loan.
 */
@Entity
@Table(
    name = "repayments",
    indexes = {
        @Index(name = "idx_repayment_receipt",  columnList = "receipt_number"),
        @Index(name = "idx_repayment_loan",     columnList = "loan_id"),
        @Index(name = "idx_repayment_date",     columnList = "payment_date"),
        @Index(name = "idx_repayment_customer", columnList = "customer_id")
    }
)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Repayment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Human-readable unique receipt number, e.g. "RCP-2026-000123".
     * Generated by RepaymentService. UNIQUE at the database level — a
     * duplicate receipt number is a fraud / audit risk and must be impossible.
     */
    @Column(name = "receipt_number", nullable = false, unique = true, length = 30)
    private String receiptNumber;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "loan_id", nullable = false)
    private Loan loan;

    /**
     * Denormalized customer reference for reporting speed. Always matches
     * loan.customer.id — enforced by the service layer at insert time.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "customer_id", nullable = false)
    private Customer customer;

    @Column(name = "payment_date", nullable = false)
    private LocalDate paymentDate;

    @Column(name = "payment_amount", nullable = false, precision = 15, scale = 2)
    private BigDecimal paymentAmount;

    @Enumerated(EnumType.STRING)
    @Column(name = "payment_method", nullable = false, length = 20)
    private PaymentMethod paymentMethod;

    /**
     * Bank / card transaction reference. Required only for BANK_TRANSFER and
     * CARD payments. Nullable for CASH (counted at the counter, no external
     * reference exists).
     */
    @Column(name = "transaction_reference", length = 100)
    private String transactionReference;

    /**
     * The user who recorded this payment (Admin or Cashier).
     * Critical for accountability: "who took this money?".
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "received_by", nullable = false, updatable = false)
    private User receivedBy;

    @Column(name = "remarks", length = 500)
    private String remarks;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @PrePersist
    protected void onCreate() {
        this.createdAt = LocalDateTime.now();
        if (this.paymentDate == null) {
            this.paymentDate = LocalDate.now();
        }
    }
}