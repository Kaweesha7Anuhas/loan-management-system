package com.example.loanmanagement.entity;

import com.example.loanmanagement.enums.CustomerStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * A customer of the finance company.
 *
 * This is the source of truth for who is borrowing money. Loan applications
 * and disbursed loans both reference a Customer.
 *
 * Design notes:
 *  - customerCode is a human-readable unique identifier (e.g. "CUS-000001"),
 *    generated by CustomerService (Phase 5), not by Hibernate.
 *  - nicNumber and email are UNIQUE at the database level — the only reliable
 *    guarantee against concurrent duplicate inserts.
 *  - CustomerStatus (ACTIVE / INACTIVE) lets us keep historical records without
 *    allowing new loans for deactivated customers.
 *  - No @Data — see User.java for the same rationale.
 */
@Entity
@Table(
    name = "customers",
    indexes = {
        @Index(name = "idx_customers_code",  columnList = "customer_code"),
        @Index(name = "idx_customers_nic",   columnList = "nic_number"),
        @Index(name = "idx_customers_phone", columnList = "phone_number"),
        @Index(name = "idx_customers_email", columnList = "email")
    }
)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Customer {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Human-readable unique identifier, e.g. "CUS-000001".
     * Generated by the service layer — the format is a product decision,
     * not a persistence concern, so the entity does not enforce it.
     */
    @Column(name = "customer_code", nullable = false, unique = true, length = 20)
    private String customerCode;

    @Column(name = "first_name", nullable = false, length = 50)
    private String firstName;

    @Column(name = "last_name", nullable = false, length = 50)
    private String lastName;

    /**
     * National Identity Card number. Unique per person.
     * For an educational project we use fictional values.
     */
    @Column(name = "nic_number", nullable = false, unique = true, length = 20)
    private String nicNumber;

    @Column(name = "date_of_birth")
    private LocalDate dateOfBirth;

    @Column(name = "email", nullable = false, unique = true, length = 100)
    private String email;

    @Column(name = "phone_number", nullable = false, length = 20)
    private String phoneNumber;

    @Column(name = "address", nullable = false, length = 255)
    private String address;

    @Column(name = "city", length = 100)
    private String city;

    @Column(name = "occupation", length = 100)
    private String occupation;

    /**
     * Monthly income in LKR. Nullable — not every applicant discloses this
     * at registration.
     */
    @Column(name = "monthly_income", precision = 15, scale = 2)
    private BigDecimal monthlyIncome;

    /**
     * STRING storage — never ORDINAL. Reordering the CustomerStatus enum
     * must never silently flip an existing customer's status.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "customer_status", nullable = false, length = 20)
    @Builder.Default
    private CustomerStatus customerStatus = CustomerStatus.ACTIVE;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    @PreUpdate
    protected void onUpdate() {
        this.updatedAt = LocalDateTime.now();
    }

    /**
     * Convenience: full name for display in lists / details.
     * Not persisted — derived at read time.
     */
    public String getFullName() {
        return (firstName == null ? "" : firstName)
                + " "
                + (lastName == null ? "" : lastName);
    }
}