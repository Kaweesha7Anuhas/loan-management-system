package com.example.loanmanagement.entity;

import com.example.loanmanagement.enums.LoanStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * A disbursed loan — the actual financial account the customer repays.
 *
 * Created exactly once per approved LoanApplication (enforced by the UNIQUE
 * constraint on loan_application_id). This is the point where money leaves
 * the company; every field here is financially significant and must NEVER be
 * silently modified after disbursement.
 *
 * Frozen terms (snapshot at disbursement, not lookups):
 *  - principalAmount
 *  - annualInterestRate
 *  - tenureMonths
 *  - totalPayable
 *
 * Running balance fields (updated transactionally on each repayment):
 *  - totalPaid
 *  - outstandingBalance
 */
@Entity
@Table(
    name = "loans",
    indexes = {
        @Index(name = "idx_loans_account_number", columnList = "loan_account_number"),
        @Index(name = "idx_loans_customer",       columnList = "customer_id"),
        @Index(name = "idx_loans_status",         columnList = "loan_status")
    }
)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Loan {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Human-readable unique loan account number, e.g. "LN-2026-000001".
     * Generated by LoanDisbursementService.
     */
    @Column(name = "loan_account_number", nullable = false, unique = true, length = 30)
    private String loanAccountNumber;

    /**
     * The approved application that produced this loan.
     * UNIQUE on loan_application_id = the structural guarantee against
     * double-disbursement.
     */
    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "loan_application_id", nullable = false, unique = true)
    private LoanApplication loanApplication;

    /**
     * Customer this loan belongs to. Denormalized reference — same customer
     * as loanApplication.customer, but kept as a direct FK so queries and
     * reports don't need two joins.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "customer_id", nullable = false)
    private Customer customer;

    // ─────────────────────────────────────────────
    // FROZEN TERMS (snapshot at disbursement)
    // ─────────────────────────────────────────────

    @Column(name = "principal_amount", nullable = false, precision = 15, scale = 2)
    private BigDecimal principalAmount;

    @Column(name = "annual_interest_rate", nullable = false, precision = 5, scale = 2)
    private BigDecimal annualInterestRate;

    @Column(name = "tenure_months", nullable = false)
    private Integer tenureMonths;

    /**
     * Total amount the customer will repay over the life of the loan
     * (principal + all interest). Frozen at disbursement.
     */
    @Column(name = "total_payable", nullable = false, precision = 15, scale = 2)
    private BigDecimal totalPayable;

    // ─────────────────────────────────────────────
    // DATES
    // ─────────────────────────────────────────────

    @Column(name = "disbursement_date", nullable = false)
    private LocalDate disbursementDate;

    /**
     * The final due date of the last instalment (disbursementDate + tenure).
     */
    @Column(name = "maturity_date", nullable = false)
    private LocalDate maturityDate;

    // ─────────────────────────────────────────────
    // RUNNING BALANCES (updated on every repayment)
    // ─────────────────────────────────────────────

    @Column(name = "total_paid", nullable = false, precision = 15, scale = 2)
    @Builder.Default
    private BigDecimal totalPaid = BigDecimal.ZERO;

    /**
     * Amount still owed by the customer.
     * At disbursement = totalPayable.
     * Decreases with each repayment, reaches exactly 0 when fully paid.
     * Recaculated transactionally on every repayment recording.
     */
    @Column(name = "outstanding_balance", nullable = false, precision = 15, scale = 2)
    private BigDecimal outstandingBalance;

    @Enumerated(EnumType.STRING)
    @Column(name = "loan_status", nullable = false, length = 20)
    @Builder.Default
    private LoanStatus loanStatus = LoanStatus.ACTIVE;

    // ─────────────────────────────────────────────
    // Timestamps
    // ─────────────────────────────────────────────

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    @PreUpdate
    protected void onUpdate() {
        this.updatedAt = LocalDateTime.now();
    }
}